"""Generate compact LM simple casing tables from Unicode 16.0.0 UnicodeData.txt (ADR-063)."""
from __future__ import annotations

import hashlib
from pathlib import Path
import sys
import tempfile
import urllib.request

UNICODE_DATA_URL = "https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt"
RECORDED_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"

ROOT = Path(__file__).resolve().parents[1]
PY_OUT = ROOT / "lm" / "unicode_tables.py"
GO_OUT = ROOT / "lm" / "runtime" / "go" / "unicode_tables.go"


def fetch_or_read_data(path_arg: str | None = None) -> tuple[str, str]:
    if path_arg:
        p = Path(path_arg)
        raw = p.read_bytes()
        h = hashlib.sha256(raw).hexdigest()
        return raw.decode("utf-8"), h

    # Check common temp locations first to avoid re-downloading
    for candidate in ("/tmp/UnicodeData-16.0.0.txt", "/tmp/UnicodeData.txt"):
        cp = Path(candidate)
        if cp.exists():
            raw = cp.read_bytes()
            h = hashlib.sha256(raw).hexdigest()
            if h == RECORDED_SHA256:
                return raw.decode("utf-8"), h

    # Download to temp dir
    with tempfile.TemporaryDirectory() as td:
        tmp_file = Path(td) / "UnicodeData.txt"
        urllib.request.urlretrieve(UNICODE_DATA_URL, tmp_file)
        raw = tmp_file.read_bytes()
        h = hashlib.sha256(raw).hexdigest()
        return raw.decode("utf-8"), h


def build_ranges(mapping: dict[int, int]) -> list[tuple[int, int, int, int]]:
    cps = sorted(mapping.keys())
    ranges: list[tuple[int, int, int, int]] = []
    i = 0
    while i < len(cps):
        cp = cps[i]
        delta = mapping[cp] - cp

        # Attempt step=1 range
        j = i + 1
        while j < len(cps) and cps[j] == cps[j - 1] + 1 and mapping[cps[j]] - cps[j] == delta:
            j += 1
        len1 = j - i

        # Attempt step=2 range
        k = i + 1
        while k < len(cps) and cps[k] == cps[k - 1] + 2 and mapping[cps[k]] - cps[k] == delta:
            k += 1
        len2 = k - i

        if len1 >= 2 and len1 >= len2:
            ranges.append((cp, cps[j - 1], delta, 1))
            i = j
        elif len2 >= 2:
            ranges.append((cp, cps[k - 1], delta, 2))
            i = k
        else:
            ranges.append((cp, cp, delta, 1))
            i += 1
    return ranges


def format_py_tuples(ranges: list[tuple[int, int, int, int]], per_line: int = 4) -> str:
    lines = []
    for i in range(0, len(ranges), per_line):
        chunk = ranges[i:i + per_line]
        parts = [f"({lo}, {hi}, {delta}, {step})" for lo, hi, delta, step in chunk]
        lines.append("    " + ", ".join(parts) + ",")
    return "\n".join(lines)


def format_go_structs(ranges: list[tuple[int, int, int, int]], per_line: int = 4) -> str:
    lines = []
    for i in range(0, len(ranges), per_line):
        chunk = ranges[i:i + per_line]
        parts = [f"{{{lo}, {hi}, {delta}, {step}}}" for lo, hi, delta, step in chunk]
        lines.append("\t" + ", ".join(parts) + ",")
    return "\n".join(lines)


def generate_py(upper_ranges: list[tuple[int, int, int, int]], lower_ranges: list[tuple[int, int, int, int]]) -> str:
    return f'''"""LM Unicode tables v1.
Generated by bench/gen_unicode_tables.py from Unicode 16.0.0 UnicodeData.txt
SHA-256: {RECORDED_SHA256}
"""
from __future__ import annotations

from bisect import bisect_right

# Compact simple casing tables: (lo, hi, delta, step)
UPPER_RANGES = (
{format_py_tuples(upper_ranges)}
)

LOWER_RANGES = (
{format_py_tuples(lower_ranges)}
)

_UPPER_KEYS = tuple(r[0] for r in UPPER_RANGES)
_LOWER_KEYS = tuple(r[0] for r in LOWER_RANGES)


def to_upper_code(cp: int) -> int:
    if 97 <= cp <= 122:
        return cp - 32
    idx = bisect_right(_UPPER_KEYS, cp) - 1
    if idx >= 0:
        lo, hi, delta, step = UPPER_RANGES[idx]
        if cp <= hi and (cp - lo) % step == 0:
            return cp + delta
    return cp


def to_lower_code(cp: int) -> int:
    if 65 <= cp <= 90:
        return cp + 32
    idx = bisect_right(_LOWER_KEYS, cp) - 1
    if idx >= 0:
        lo, hi, delta, step = LOWER_RANGES[idx]
        if cp <= hi and (cp - lo) % step == 0:
            return cp + delta
    return cp


def to_upper_str(s: str) -> str:
    return "".join(chr(to_upper_code(ord(c))) for c in s)


def to_lower_str(s: str) -> str:
    return "".join(chr(to_lower_code(ord(c))) for c in s)
'''


def generate_go(upper_ranges: list[tuple[int, int, int, int]], lower_ranges: list[tuple[int, int, int, int]]) -> str:
    return f'''// LM Unicode tables v1
// Generated by bench/gen_unicode_tables.py from Unicode 16.0.0 UnicodeData.txt
// SHA-256: {RECORDED_SHA256}
package main

import "sort"

type caseRange struct {{
	lo, hi, delta, step int32
}}

var upperRanges = [...]caseRange{{
{format_go_structs(upper_ranges)}
}}

var lowerRanges = [...]caseRange{{
{format_go_structs(lower_ranges)}
}}

func toUpperRune(r rune) rune {{
	if r >= 'a' && r <= 'z' {{
		return r - 32
	}}
	cp := int32(r)
	i := sort.Search(len(upperRanges), func(i int) bool {{
		return upperRanges[i].lo > cp
	}}) - 1
	if i >= 0 {{
		cr := upperRanges[i]
		if cp <= cr.hi && (cp-cr.lo)%cr.step == 0 {{
			return rune(cp + cr.delta)
		}}
	}}
	return r
}}

func toLowerRune(r rune) rune {{
	if r >= 'A' && r <= 'Z' {{
		return r + 32
	}}
	cp := int32(r)
	i := sort.Search(len(lowerRanges), func(i int) bool {{
		return lowerRanges[i].lo > cp
	}}) - 1
	if i >= 0 {{
		cr := lowerRanges[i]
		if cp <= cr.hi && (cp-cr.lo)%cr.step == 0 {{
			return rune(cp + cr.delta)
		}}
	}}
	return r
}}

func toUpperString(s string) string {{
	runes := []rune(s)
	for i, r := range runes {{
		runes[i] = toUpperRune(r)
	}}
	return string(runes)
}}

func toLowerString(s string) string {{
	runes := []rune(s)
	for i, r := range runes {{
		runes[i] = toLowerRune(r)
	}}
	return string(runes)
}}

// toValidUTF8 sanitizes s by replacing every invalid UTF-8 byte sequence with U+FFFD (Unicode maximal subpart).
func toValidUTF8(s string) string {{
	b := []byte(s)
	var out []rune
	n := len(b)
	i := 0
	for i < n {{
		c0 := b[i]
		if c0 < 0x80 {{
			out = append(out, rune(c0))
			i++
			continue
		}}
		if c0 >= 0xC2 && c0 <= 0xDF {{
			if i+1 < n && b[i+1] >= 0x80 && b[i+1] <= 0xBF {{
				out = append(out, rune(c0&0x1F)<<6|rune(b[i+1]&0x3F))
				i += 2
				continue
			}}
			out = append(out, 0xFFFD)
			i++
			continue
		}}
		if c0 >= 0xE0 && c0 <= 0xEF {{
			valid2 := false
			if i+1 < n {{
				c1 := b[i+1]
				if (c0 == 0xE0 && c1 >= 0xA0 && c1 <= 0xBF) ||
					(c0 >= 0xE1 && c0 <= 0xEC && c1 >= 0x80 && c1 <= 0xBF) ||
					(c0 == 0xED && c1 >= 0x80 && c1 <= 0x9F) ||
					(c0 >= 0xEE && c0 <= 0xEF && c1 >= 0x80 && c1 <= 0xBF) {{
					valid2 = true
				}}
			}}
			if valid2 {{
				if i+2 < n && b[i+2] >= 0x80 && b[i+2] <= 0xBF {{
					out = append(out, rune(c0&0x0F)<<12|rune(b[i+1]&0x3F)<<6|rune(b[i+2]&0x3F))
					i += 3
					continue
				}}
				out = append(out, 0xFFFD)
				i += 2
				continue
			}}
			out = append(out, 0xFFFD)
			i++
			continue
		}}
		if c0 >= 0xF0 && c0 <= 0xF4 {{
			valid2 := false
			if i+1 < n {{
				c1 := b[i+1]
				if (c0 == 0xF0 && c1 >= 0x90 && c1 <= 0xBF) ||
					(c0 >= 0xF1 && c0 <= 0xF3 && c1 >= 0x80 && c1 <= 0xBF) ||
					(c0 == 0xF4 && c1 >= 0x80 && c1 <= 0x8F) {{
					valid2 = true
				}}
			}}
			if valid2 {{
				if i+2 < n && b[i+2] >= 0x80 && b[i+2] <= 0xBF {{
					if i+3 < n && b[i+3] >= 0x80 && b[i+3] <= 0xBF {{
						out = append(out, rune(c0&0x07)<<18|rune(b[i+1]&0x3F)<<12|rune(b[i+2]&0x3F)<<6|rune(b[i+3]&0x3F))
						i += 4
						continue
					}}
					out = append(out, 0xFFFD)
					i += 3
					continue
				}}
				out = append(out, 0xFFFD)
				i += 2
				continue
			}}
			out = append(out, 0xFFFD)
			i++
			continue
		}}
		out = append(out, 0xFFFD)
		i++
	}}
	return string(out)
}}

func cleanArgs(args []string) []string {{
	out := make([]string, len(args))
	for i, a := range args {{
		out[i] = toValidUTF8(a)
	}}
	return out
}}
'''


def main(path_arg: str | None = None) -> int:
    text, h = fetch_or_read_data(path_arg)
    if h != RECORDED_SHA256:
        sys.stderr.write(f"SHA-256 mismatch: expected {RECORDED_SHA256}, got {h}\n")
        return 1

    upper_map: dict[int, int] = {}
    lower_map: dict[int, int] = {}
    for line in text.splitlines():
        if not line or ";" not in line:
            continue
        fields = line.split(";")
        cp = int(fields[0], 16)
        if len(fields) > 12 and fields[12]:
            upper_map[cp] = int(fields[12], 16)
        if len(fields) > 13 and fields[13]:
            lower_map[cp] = int(fields[13], 16)

    upper_ranges = build_ranges(upper_map)
    lower_ranges = build_ranges(lower_map)

    py_code = generate_py(upper_ranges, lower_ranges)
    PY_OUT.write_text(py_code, encoding="utf-8")

    go_code = generate_go(upper_ranges, lower_ranges)
    GO_OUT.write_text(go_code, encoding="utf-8")

    print(f"Unicode 16.0.0 SHA-256: {h}")
    print(f"Upper table size: {len(upper_ranges)} ranges ({len(upper_map)} mappings)")
    print(f"Lower table size: {len(lower_ranges)} ranges ({len(lower_map)} mappings)")
    print(f"Written: {PY_OUT.relative_to(ROOT)} ({len(py_code.splitlines())} lines)")
    print(f"Written: {GO_OUT.relative_to(ROOT)} ({len(go_code.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    arg = sys.argv[1] if len(sys.argv) > 1 else None
    sys.exit(main(arg))
